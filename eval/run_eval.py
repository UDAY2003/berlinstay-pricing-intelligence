"""Evaluate the text-to-SQL assistant.

  python -m eval.run_eval --validate-gold            # no LLM: gold SQL must pass the safety layer and return rows
  python -m eval.run_eval --provider env             # uses LLM_PROVIDER / LLM_API_KEY / LLM_MODEL from the environment
  python -m eval.run_eval --provider env --limit 10  # quick run

Scoring = EXECUTION ACCURACY: the result of the generated SQL must match the result of the gold SQL
(values compared, column names ignored, floats rounded, extra columns tolerated, row order checked only when the question asks for an order).
'refuse' questions (unanswerable or adversarial) pass if the assistant did not return data: validation rejected, or the explicit
'cannot be answered' message. Writes eval/results_<model>.json and docs/EVAL_REPORT.md.
"""
import argparse
import json
import time
from collections import defaultdict
import pandas as pd
from src.config import ROOT
from src.text2sql.engine import ask
from src.text2sql.llm import get_provider
from src.text2sql.safety import make_connection, execute_safe
from src.text2sql.schema import ALLOWED_TABLES

QUESTIONS = ROOT / "eval" / "questions.jsonl"


def load_questions():
    return [json.loads(l) for l in QUESTIONS.read_text(encoding="utf-8").splitlines() if l.strip()]


def _col_key(s: pd.Series, ordered: bool):
    v = [round(float(x), 2) if isinstance(x, (int, float)) and not isinstance(x, bool) and x == x else (str(x) if x == x else "nan") for x in s.tolist()]
    return tuple(v) if ordered else tuple(sorted(v, key=str))


def results_match(gold: pd.DataFrame, got: pd.DataFrame, ordered: bool) -> bool:
    if got is None or len(gold) != len(got):
        return False
    gcols = [_col_key(gold[c], ordered) for c in gold.columns]
    ocols = [_col_key(got[c], ordered) for c in got.columns]
    pool = list(ocols)
    for g in gcols:
        if g in pool:
            pool.remove(g)
        else:
            return False
    return True


def is_refusal(ans) -> bool:
    if ans.stage != "ok":
        return True
    return ans.df is not None and len(ans.df) == 1 and "cannot be answered" in str(ans.df.iloc[0, 0]).lower()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--provider", default=None, help="'env' to use environment configuration")
    ap.add_argument("--validate-gold", action="store_true")
    ap.add_argument("--limit", type=int, default=None)
    args = ap.parse_args()
    qs = load_questions()[: args.limit]
    con = make_connection(ROOT / "app" / "data")

    if args.validate_gold:
        bad = 0
        for q in qs:
            if q["expect"] != "result":
                continue
            try:
                df, _, _ = execute_safe(con, q["gold_sql"], ALLOWED_TABLES)
                assert len(df) > 0
            except Exception as e:
                bad += 1
                print(f"GOLD FAILS {q['id']}: {e}")
        n = sum(q["expect"] == "result" for q in qs)
        print(f"gold SQL valid and non-empty: {n - bad}/{n}")
        return bad

    provider = get_provider()
    if provider is None:
        raise SystemExit("No LLM configured. Set LLM_PROVIDER (anthropic|openai), LLM_API_KEY and optionally LLM_MODEL, then rerun.")
    rows, t0 = [], time.time()
    for q in qs:
        ans = ask(q["question"], provider, con)
        if q["expect"] == "refuse":
            ok = is_refusal(ans)
        else:
            gold, _, _ = execute_safe(con, q["gold_sql"], ALLOWED_TABLES)
            ok = ans.stage == "ok" and results_match(gold, ans.df, q["ordered"])
        rows.append(dict(id=q["id"], category=q["category"], question=q["question"], ok=bool(ok), stage=ans.stage, repaired=len(ans.attempts) > 1,
                         generated_sql=ans.sql, error=ans.error, gold_sql=q["gold_sql"]))
        print(f"{'PASS' if ok else 'FAIL'} {q['id']} [{q['category']}] {q['question'][:70]}")
    res = pd.DataFrame(rows)
    acc = res.ok.mean()
    by_cat = res.groupby("category").ok.agg(["mean", "size"])
    out = {"model": provider.model, "provider": provider.name, "n": len(res), "accuracy": float(acc), "seconds": round(time.time() - t0),
           "by_category": {k: {"accuracy": float(v["mean"]), "n": int(v["size"])} for k, v in by_cat.iterrows()}, "rows": rows}
    safe = provider.model.replace("/", "_").replace(":", "_")
    (ROOT / "eval" / f"results_{safe}.json").write_text(json.dumps(out, indent=2, ensure_ascii=False), encoding="utf-8")
    write_report(out, res)
    print(f"\nexecution accuracy {acc:.1%} ({int(res.ok.sum())}/{len(res)})")


def write_report(o, res):
    L = ["# Text-to-SQL evaluation report", "",
         f"Model: `{o['provider']}:{o['model']}` | questions: {o['n']} | **execution accuracy: {o['accuracy']:.1%}** | run time {o['seconds']} s", "",
         "Generated by `python -m eval.run_eval --provider env`. Scoring rules are in `eval/run_eval.py`.", "",
         "| Category | Accuracy | n |", "|---|---|---|"]
    L += [f"| {k} | {v['accuracy']:.0%} | {v['n']} |" for k, v in o["by_category"].items()]
    rep = res[res.repaired & res.ok]
    L += ["", f"Questions fixed by the one-shot self-repair step: {len(rep)}.", "", "## Failures", ""]
    for r in res[~res.ok].itertuples():
        L += [f"### {r.id} ({r.category}): {r.question}", f"- stage: `{r.stage}` | error: {r.error}", f"- generated: `{(r.generated_sql or '')[:600]}`", f"- gold: `{r.gold_sql[:600]}`", "",
              "- diagnosis / fix: _to be written after reading the failure_", ""]
    (ROOT / "docs" / "EVAL_REPORT.md").write_text("\n".join(L) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
