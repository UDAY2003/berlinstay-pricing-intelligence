"""V2 before/after: compare every V1 table (plain SQL) with its dbt rebuild, using EXCEPT in both directions.

Writes docs/V1_V2_RECONCILIATION.md. Columns compared = columns of the V1 table (so dbt may add columns).
"""
import duckdb
from src.config import DB_PATH, DOCS_DIR

PAIRS = [("mart", "dbt_mart", t) for t in ["dim_neighbourhood", "dim_host_type", "dim_date", "dim_listing", "fact_listing",
                                           "fact_listing_day", "fact_review_month", "fact_availability_week"]]
PAIRS += [("analysis", "dbt_analysis", t) for t in ["price_by_district_roomtype", "supply_concentration", "multi_listing_hosts",
          "occupancy_revenue", "monthly_review_series", "seasonal_index", "forward_availability_weekly",
          "forward_availability_events", "review_demand_trends", "license_status", "neighbourhood_summary"]]
# Known intentional differences (documented, with the reason)
KNOWN = {"dim_listing": "is_benchmark: V1 returned NULL for unpriced listings (three-valued logic), dbt returns FALSE. "
                        "Caught by the dbt not_null test. No V1 query result changes."}


def main():
    con = duckdb.connect(str(DB_PATH), read_only=True)
    rows = []
    for v1s, v2s, t in PAIRS:
        cols = [r[0] for r in con.execute(f"SELECT column_name FROM information_schema.columns WHERE table_schema='{v1s}' AND table_name='{t}' ORDER BY ordinal_position").fetchall()]
        sel = ", ".join(f'"{c}"' for c in cols)
        n1 = con.execute(f"SELECT COUNT(*) FROM {v1s}.{t}").fetchone()[0]
        n2 = con.execute(f"SELECT COUNT(*) FROM {v2s}.{t}").fetchone()[0]
        a = con.execute(f"SELECT COUNT(*) FROM (SELECT {sel} FROM {v1s}.{t} EXCEPT SELECT {sel} FROM {v2s}.{t})").fetchone()[0]
        b = con.execute(f"SELECT COUNT(*) FROM (SELECT {sel} FROM {v2s}.{t} EXCEPT SELECT {sel} FROM {v1s}.{t})").fetchone()[0]
        rows.append((t, n1, n2, a, b))
    lines = ["# V1 vs V2 (dbt) reconciliation", "",
             "Generated by `python -m src.reconcile_v1_dbt`. Each V1 table (plain SQL, `sql/`) is compared with the dbt rebuild (`dbt_project/`) "
             "using `EXCEPT` in both directions over the V1 columns. Zero differing rows = identical results.", "",
             "| table | V1 rows | dbt rows | in V1 not dbt | in dbt not V1 | status |", "|---|---|---|---|---|---|"]
    for t, n1, n2, a, b in rows:
        status = "identical" if (n1 == n2 and a == 0 and b == 0) else ("DIFFERS (known, see below)" if t in KNOWN else "DIFFERS")
        lines.append(f"| {t} | {n1:,} | {n2:,} | {a:,} | {b:,} | {status} |")
    lines += ["", "## Known intentional differences", ""] + [f"- **{k}**: {v}" for k, v in KNOWN.items()]
    (DOCS_DIR / "V1_V2_RECONCILIATION.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return rows


if __name__ == "__main__":
    main()
